BEGIN;

DO $$
BEGIN
    IF current_database() <> 'sql_postgresql_practice' THEN
        RAISE EXCEPTION 'Hãy kết nối database sql_postgresql_practice trước khi chạy';
    END IF;
END $$;

-- BY DEFAULT cho phép seed ID cố định. Khi ứng dụng bỏ id, sequence tự cấp ID.
CREATE TABLE public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_pk PRIMARY KEY (id),
    CONSTRAINT users_email_uq UNIQUE (email),
    CONSTRAINT users_name_ck CHECK (length(btrim(name)) > 0),
    -- Quy ước học tập: email đã trim/lowercase; không phải validator email đầy đủ.
    CONSTRAINT users_email_ck CHECK (
        email = btrim(email) AND email = lower(email) AND position('@' IN email) > 1
    )
);

CREATE TABLE public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    CONSTRAINT categories_pk PRIMARY KEY (id),
    CONSTRAINT categories_name_uq UNIQUE (name),
    CONSTRAINT categories_name_ck CHECK (length(btrim(name)) > 0)
);

CREATE TABLE public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    price NUMERIC(14, 2) NOT NULL,
    stock INTEGER NOT NULL DEFAULT 0,
    category_id BIGINT NOT NULL,
    CONSTRAINT products_pk PRIMARY KEY (id),
    CONSTRAINT products_name_ck CHECK (length(btrim(name)) > 0),
    CONSTRAINT products_price_ck CHECK (price >= 0 AND price <> 'NaN'::numeric),
    CONSTRAINT products_stock_ck CHECK (stock >= 0),
    CONSTRAINT products_category_fk FOREIGN KEY (category_id)
        REFERENCES public.categories (id) ON DELETE RESTRICT
);

CREATE TABLE public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    total NUMERIC(14, 2) NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT orders_pk PRIMARY KEY (id),
    CONSTRAINT orders_user_fk FOREIGN KEY (user_id)
        REFERENCES public.users (id) ON DELETE RESTRICT,
    CONSTRAINT orders_total_ck CHECK (total >= 0 AND total <> 'NaN'::numeric),
    CONSTRAINT orders_status_ck CHECK (status IN ('pending', 'paid', 'shipped', 'cancelled'))
);

CREATE TABLE public.order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    price NUMERIC(14, 2) NOT NULL,
    CONSTRAINT order_items_pk PRIMARY KEY (id),
    CONSTRAINT order_items_order_fk FOREIGN KEY (order_id)
        REFERENCES public.orders (id) ON DELETE CASCADE,
    CONSTRAINT order_items_product_fk FOREIGN KEY (product_id)
        REFERENCES public.products (id) ON DELETE RESTRICT,
    CONSTRAINT order_items_order_product_uq UNIQUE (order_id, product_id),
    CONSTRAINT order_items_quantity_ck CHECK (quantity > 0),
    CONSTRAINT order_items_price_ck CHECK (price >= 0 AND price <> 'NaN'::numeric)
);

-- order_items.price là đơn giá lúc mua, không phải products.price hiện tại.
-- total là dữ liệu lưu dư có chủ ý để luyện backend: CHECK không tự kiểm tra
-- SUM(order_items.quantity * order_items.price) từ bảng khác.
-- Service/transaction phải giữ total khớp dòng hàng; workspace chưa dùng trigger.
-- Chưa tạo index phụ để quan sát bài 18. PK/UNIQUE đã tự tạo index tương ứng.
COMMIT;
